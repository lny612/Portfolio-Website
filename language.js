const textEntries = [];
const managedEntries = JSON.parse(document.querySelector('#site-copy-data')?.textContent || '[]').map(entry=>{
  let node=document.documentElement;
  for(const index of entry.path)node=node?.childNodes[index];
  return {...entry,node};
}).filter(entry=>entry.node?.nodeType===3);
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest('script, style, [data-language-switch], [data-bilingual]')) continue;
  const key = node.textContent.trim();
  if (Object.hasOwn(korean, key)) textEntries.push({ node, english: node.textContent, key });
}
const attributeEntries = [];
document.querySelectorAll('[aria-label], [alt], [data-ko-title]').forEach(node => {
  for (const attribute of ['aria-label', 'alt', 'title']) {
    const english = node.getAttribute(attribute);
    const translated = node.getAttribute('data-ko-' + attribute) || korean[english];
    if (english && translated) attributeEntries.push({ node, attribute, english, translated });
  }
});
