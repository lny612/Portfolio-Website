function setLanguage(language, announce = false) {
  const ko = language === 'ko';
  document.documentElement.lang = language;
  for (const {node, english, key} of textEntries) {
    node.textContent = ko ? english.replace(key, korean[key]) : english;
  }
  for(const entry of managedEntries)entry.node.textContent=ko?entry.ko:entry.en;
  for (const {node, attribute, english, translated} of attributeEntries) {
    node.setAttribute(attribute, ko ? translated : english);
  }
  document.title = ko ? (document.documentElement.getAttribute?.('data-ko-title') || '임나영 — 게임 기획자 & 프로그래머') : englishTitle;
  description.content = ko ? (description.getAttribute?.('data-ko-content') || '게임 기획자이자 프로그래머 임나영의 포트폴리오. 게임 시스템, 창의적인 프로토타입, 출시 프로젝트를 소개합니다.') : englishDescription;
  switcher.setAttribute('aria-label', ko ? '언어 선택' : 'Select language');
  switcher.querySelectorAll('button').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === language));
    button.setAttribute('aria-label', button.dataset.lang === 'ko' ? '한국어로 보기' : 'View in English');
  });
  try { localStorage.setItem('portfolio-language', language); } catch { /* File previews or private browsing may restrict storage. */ }
  if (announce) status.textContent = ko ? '한국어로 변경되었습니다.' : 'Language changed to English.';
  // Update scroll progress after line wrapping changes the page height.
  window.dispatchEvent(new Event('resize'));
}
switcher.addEventListener('click', event => {
  const button = event.target.closest('button[data-lang]');
  if (!button || button.getAttribute('aria-pressed') === 'true') return;
  setLanguage(button.dataset.lang, true);
});
let savedLanguage;
try { savedLanguage = localStorage.getItem('portfolio-language'); } catch { /* Keep the English default when storage is unavailable. */ }
setLanguage(savedLanguage === 'ko' ? 'ko' : 'en');
